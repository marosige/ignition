import Foundation

/// Everything that turns a merged profile into a configured Mac.
public enum Setup {

    public typealias Log = (String) -> Void

    // MARK: Dock

    /// Reads the current Dock layout from the user's preferences.
    public static func currentDock() -> [DockItem] {
        func items(_ key: String, folders: Bool) -> [DockItem] {
            guard let list = CFPreferencesCopyAppValue(key as CFString, "com.apple.dock" as CFString) as? [[String: Any]] else { return [] }
            return list.compactMap { entry in
                let type = entry["tile-type"] as? String ?? ""
                if type.contains("spacer") { return DockItem(kind: type.contains("small") ? .spacer : .largeSpacer) }
                guard let data = entry["tile-data"] as? [String: Any],
                      let file = data["file-data"] as? [String: Any],
                      let urlString = file["_CFURLString"] as? String,
                      let url = URL(string: urlString) else { return nil }
                let path = url.path.hasSuffix("/") && url.path.count > 1 ? String(url.path.dropLast()) : url.path
                return DockItem(kind: folders ? .folder : .app, path: path)
            }
        }
        return items("persistent-apps", folders: false) + items("persistent-others", folders: true)
    }

    public static func applyDock(_ items: [DockItem], log: Log) -> Bool {
        guard Shell.which("dockutil") else { log("dockutil is missing – install it from Brewfile first"); return false }
        var ok = true
        func dockutil(_ args: [String]) {
            if !Shell.run("dockutil", args + ["--no-restart"]).ok { ok = false }
        }
        dockutil(["--remove", "all"])
        Thread.sleep(forTimeInterval: 1)
        for item in items {
            switch item.kind {
            case .spacer:
                log("adding small spacer")
                dockutil(["--add", "", "--type", "small-spacer", "--section", "apps"])
            case .largeSpacer:
                log("adding large spacer")
                dockutil(["--add", "", "--type", "spacer", "--section", "apps"])
            case .app:
                guard let path = item.path else { continue }
                if !FileManager.default.fileExists(atPath: path) { log("skipping \(item.title) (not installed)"); continue }
                log("adding [\(item.title)]")
                dockutil(["--add", path])
            case .folder:
                guard let path = item.path else { continue }
                log("adding folder [\(item.title)]")
                dockutil(["--add", expandTilde(path), "--view", "fan", "--display", "stack", "--sort", "dateadded"])
            }
        }
        Thread.sleep(forTimeInterval: 1)
        Shell.run("killall", ["Dock"])
        return ok
    }

    // MARK: Finder sidebar

    public static func applySidebar(_ items: [SidebarItem], log: Log) -> Bool {
        guard Shell.which("mysides") else { log("mysides is missing – install it from Brewfile first"); return false }
        var ok = Shell.run("mysides", ["remove", "all"]).ok
        for item in items {
            let url = URL(fileURLWithPath: expandTilde(item.path), isDirectory: true).absoluteString
            log("sidebar: \(item.name)")
            if !Shell.run("mysides", ["add", item.name, url]).ok { ok = false }
        }
        Shell.run("killall", ["Finder"])
        return ok
    }

    // MARK: Login apps

    public static func applyStartup(_ startup: Startup, log: Log) -> Bool {
        let fm = FileManager.default
        let dir = URL(fileURLWithPath: expandTilde("~/.ignition"), isDirectory: true)
        let script = dir.appendingPathComponent("startup.sh")
        let plist = URL(fileURLWithPath: expandTilde("~/Library/LaunchAgents/me.marosi.ignition.startup.plist"))
        do {
            try fm.createDirectory(at: dir, withIntermediateDirectories: true)
            try fm.createDirectory(at: plist.deletingLastPathComponent(), withIntermediateDirectories: true)
            var sh = "#!/usr/bin/env bash\n# Generated by Ignition\nsleep 5\n"
            for app in startup.apps { sh += "open -a \(Shell.quote(app))\n" }
            if startup.closeFinderWindows {
                sh += "sleep 10\nosascript -e 'tell application \"Finder\" to close every window'\n"
            }
            try sh.write(to: script, atomically: true, encoding: .utf8)
            try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: script.path)
            let xml = """
            <?xml version="1.0" encoding="UTF-8"?>
            <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
            <plist version="1.0">
            <dict>
                <key>Label</key><string>me.marosi.ignition.startup</string>
                <key>ProgramArguments</key><array><string>/bin/bash</string><string>\(script.path)</string></array>
                <key>RunAtLoad</key><true/>
                <key>KeepAlive</key><false/>
            </dict>
            </plist>
            """
            try xml.write(to: plist, atomically: true, encoding: .utf8)
        } catch {
            log("Startup failed: \(error.localizedDescription)")
            return false
        }
        let uid = String(getuid())
        Shell.run("launchctl", ["bootout", "gui/\(uid)", plist.path])
        let r = Shell.run("launchctl", ["bootstrap", "gui/\(uid)", plist.path])
        log("Login apps: \(startup.apps.joined(separator: ", "))")
        return r.ok
    }

    // MARK: Directories

    public static func createDirectories(_ dirs: [DirectorySpec], log: Log) -> Bool {
        var ok = true
        for d in dirs {
            let path = expandTilde(d.path)
            if FileManager.default.fileExists(atPath: path) { continue }
            do {
                try FileManager.default.createDirectory(atPath: path, withIntermediateDirectories: true)
                log("created \(d.path)")
            } catch {
                log("failed \(d.path): \(error.localizedDescription)")
                ok = false
            }
        }
        return ok
    }

    // MARK: Packages

    public static func installPackages(_ packages: Packages, log: @escaping Log) -> Bool {
        if !Brew.isInstalled {
            log("Homebrew is not installed. Opening the official installer in Terminal – run Apply again when it finishes.")
            let cmd = "/bin/bash -c \\\"$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)\\\""
            Shell.run("osascript", ["-e", "tell application \"Terminal\" to activate", "-e", "tell application \"Terminal\" to do script \"\(cmd)\""])
            return false
        }
        #if arch(arm64)
        do {
            log("Making sure Rosetta is available…")
            Shell.run("softwareupdate", ["--install-rosetta", "--agree-to-license"], onLine: log)
        }
        #endif
        // Tools Ignition itself relies on.
        let own = Packages.ignitionTools
        var merged = packages
        for e in own.brews where !merged.brews.contains(where: { $0.name == e.name }) { merged.brews.append(e) }
        for e in own.casks where !merged.casks.contains(where: { $0.name == e.name }) { merged.casks.append(e) }
        do {
            try Brew.brewfile(for: merged).write(to: AppPaths.generatedBrewfile, atomically: true, encoding: .utf8)
        } catch {
            log("Cannot write Brewfile: \(error.localizedDescription)")
            return false
        }
        log("brew bundle…")
        let r = Shell.run("brew", ["bundle", "--file=\(AppPaths.generatedBrewfile.path)"], onLine: log)
        return r.ok
    }

    // MARK: Preferences

    @discardableResult
    public static func applyPreferences(_ values: [String: PrefValue], log: Log) -> Bool {
        var ok = true
        var restart = Set<ProcessToRestart>()
        var privileged: [String] = []
        for (id, value) in values.sorted(by: { $0.key < $1.key }) {
            guard let def = PreferenceCatalog.byID[id] else { log("unknown preference \(id) – skipped"); continue }
            if def.scope == .system && def.custom == nil {
                privileged.append((["defaults"] + DefaultsService.writeArguments(def, value)).map(Shell.quote).joined(separator: " "))
            } else {
                let r = DefaultsService.write(def, value)
                if !r.ok { ok = false; log("✗ \(def.title): \(r.combined)") } else { log("✓ \(def.title)") }
            }
            restart.formUnion(def.restart)
        }
        if !privileged.isEmpty {
            let r = Shell.runPrivileged(privileged.joined(separator: "; "))
            if !r.ok { ok = false; log("✗ system preferences: \(r.combined)") } else { log("✓ \(privileged.count) system preferences") }
        }
        DefaultsService.restart(restart)
        return ok
    }

    // MARK: Dotfiles

    public static func linkDotfiles(profiles: [String], copyFiles: [String], log: Log) -> Bool {
        var ok = true
        for entry in Dotfiles.scan(profiles: profiles, copyFiles: copyFiles) {
            do { try Dotfiles.apply(entry, log: log) }
            catch { ok = false; log("✗ ~/\(entry.relativePath): \(error.localizedDescription)") }
        }
        return ok
    }
}

extension Packages {
    /// Dependencies of Ignition's own features.
    public static var ignitionTools: Packages {
        var p = Packages()
        p.brews = [PackageEntry(name: "mas", comment: "Mac App Store CLI"), PackageEntry(name: "dockutil", comment: "Dock layout")]
        p.casks = [PackageEntry(name: "mysides", comment: "Finder sidebar")]
        return p
    }
}
